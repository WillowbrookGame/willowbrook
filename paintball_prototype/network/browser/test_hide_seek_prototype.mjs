import assert from 'node:assert/strict';
import {createHideSeekPrototype} from './hide_seek_prototype.mjs';
const xyz=(x,y,z)=>({x,y,z});
const area={verified:true,zone:'test-yard',bounds:{min:xyz(-20,-.2,-20),max:xyz(20,2,20)},
  boxes:[{min:xyz(-.3,0,-1.1),max:xyz(.3,3,-.9)}]};
let t=1000;
const resolveScene=p=>p.zone==='door-load'?null:['test-yard','room:1','room:2'].includes(p.zone)?{id:p.zone,pose:p}:false;
const m=createHideSeekPrototype({areas:{'test-yard':area,'room:1':area,'room:2':area},resolveScene,admitted:p=>p?.ok===true,now:()=>t});
const player=(id,x,z)=>({profile:{id},ok:true,zone:area.zone,...xyz(x,0,z),yaw:0,grounded:true,updated:t});
const a=player('a',0,0),b=player('b',0,-2),c=player('c',1,1), outsider=player('x',0,-.3);
const act=(p,action,extra={})=>m.handle(p,{type:'hideSeek',action,...extra});
const fresh=()=>{for(const p of [a,b,c])p.updated=t;};
assert.throws(()=>createHideSeekPrototype({areas:{'test-yard':{...area,verified:false}},resolveScene,admitted:()=>true}), /known local fixture geometry/);
assert(!act({...a,ok:false},'join').ok);
for(const zone of ['private','beach','paintball']) assert(!act({...a,zone},'join').ok);
assert(!act({...a,x:99},'join').ok);
assert(act(a,'join').ok);
assert(!act(a,'start').ok);
assert(act(b,'join').ok&&act(c,'join').ok);
assert(!act({...a},'tag').ok);
assert(!act(b,'start').ok&&act(a,'start').ok);
assert(m.visible(outsider,b)&&!m.visible(a,b)&&m.view(outsider)===null);
assert(!act(a,'tag').ok);
t+=29999;fresh();assert.equal(m.view(a).phase,'hide');
t++;fresh();m.tick();assert.equal(m.view(a).phase,'seek');assert(m.visible(a,b));
assert(!act(b,'tag').ok);
assert(!act(a,'tag',{target:'x'}).ok);
assert(!act(a,'tag').ok,'near and facing, but b behind the wall and c behind avatar');
assert(!act(a,'tag').ok,'per-seeker cooldown');
t+=501;a.x=b.x=2;b.zone='door-load';fresh();assert(!act(a,'tag').ok,'transient loading excluded');
assert(m.view(b),'legal door transition retains membership');
t+=501;b.zone='room:1';fresh();assert(!act(a,'tag').ok,'different scene excluded');
assert(m.view(b),'ordinary indoor scene retains membership');
t+=501;a.zone='room:2';fresh();assert(!act(a,'tag').ok,'identical positions in different homes cannot tag');
t+=501;a.zone=b.zone=area.zone; b.zone='paintball';fresh();assert(!act(a,'tag').ok); assert.equal(m.view(b),null);

t+=501;a.x=c.x=2;c.z=-1.7;fresh();c.updated=t-701;assert(!act(a,'tag').ok,'stale target excluded');
t+=501;fresh();c.grounded=false;assert(!act(a,'tag').ok,'airborne target excluded');
t+=501;fresh();c.grounded=true;a.yaw=Math.PI;assert(!act(a,'tag').ok,'behind the seeker');
t+=501;fresh();a.yaw=0;c.z=-2.5;assert(!act(a,'tag').ok,'outside range');
t+=501;fresh();c.z=-2;assert(act(a,'tag').ok,'clear closest eligible member, not outsider');
assert(m.view(c).found&&m.view(a).result==='seeker');
assert(!act(a,'tag').ok,'cannot tag twice or after results');
t+=20001;m.tick();assert.equal(m.view(a),null);
a.x=2;b.zone=area.zone;assert(act(a,'join').ok&&act(b,'join').ok&&act(a,'start').ok);
t+=210001;m.tick();assert.equal(m.view(b).result,'hiders');
assert(act(a,'leave').ok&&act(b,'leave').ok);
assert(act(a,'join').ok&&act(b,'join').ok);
assert(act(a,'leave').ok&&m.view(b).host,'waiting host migration');
assert(act(a,'join').ok&&act(b,'start').ok);
a.zone='door-load';m.tick();t+=8000;m.tick();
assert.equal(m.view(a),null,'unresolved transition expires');
assert.equal(m.view(b).result,'seeker');
assert(act(b,'leave').ok);
a.zone=b.zone='room:1';a.x=2;a.z=0;a.yaw=0;b.x=2;b.z=-1.8;
assert(act(a,'join').ok&&act(b,'join').ok&&act(a,'start').ok);
t+=30000;fresh();m.tick();assert(act(a,'tag').ok&&m.view(b).found,'same authorized room clear tag');
console.log('PASS isolated Hide and Seek prototype: admission, scene/bounds, countdown/roles/privacy, rejects wrong target data, occlusion/facing/range/grounded/stale/cooldown, single valid tag, both endings, reset and lobby migration.');
