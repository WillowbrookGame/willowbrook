import {createPaintballLobbies} from './paintball_lobby_preview.mjs';
import assert from 'node:assert/strict';
let now=1000, ongoing=false, disabled=false, opens=[],holdLaunch;
const peers=[1,2,3,4,5,6].map(id=>({profile:{id,username:'player'+id},up:true,at:true,messages:[]}));
const [a,b,c,d,e,f]=peers;
const l=createPaintballLobbies({admitted:p=>p.up,nearDoor:p=>p.at,send:(p,m)=>p.messages.push(m),authority:{
 ready:()=>!disabled,busy:()=>ongoing,active:()=>false,
 async start(room,host,rev){opens.push({host:host.account,accounts:room.slots.map(s=>s.account)});
  if(holdLaunch)await holdLaunch;
  if(room.revision!==rev)return {ok:false,error:'Roster changed during load.'};
  ongoing=true;return {ok:true};}
}});
const ask=(p,action,m={})=>l.handle(p,{type:'paintballLobby',action,...m},now++);
const ready=(p,r=true)=>ask(p,'ready',{ready:r});
const last=(p)=>p.messages.at(-1);
const room=(p)=>p.messages.findLast(m=>m.room)?.room;
const wait=()=>new Promise(r=>setTimeout(r,1));
await ask(a,'join');await ready(a);
assert.equal(opens.length,0);assert(room(a).humans[0].ready);
await ask(b,'join');
assert.deepEqual(room(a).humans.map(h=>h.ready),[true,false]);
assert.equal(opens.length,0);
await ready(b);
assert.deepEqual(opens,[{host:1,accounts:[1,2]}]);
await ask(c,'join');await ready(c);await ask(d,'join');await ready(d);
assert(room(c).arenaBusy);assert.equal(opens.length,1);
await ask(e,'join');await ask(f,'join');
const g={profile:{id:7,username:'g'},up:true,at:true,messages:[]};
await ask(g,'join');assert.match(last(g).error,/full/);
await ask(e,'leave');await ask(f,'leave');
assert.deepEqual(room(c).humans.map(h=>h.ready),[false,false]);
ongoing=false;l.tick(now);await wait();assert.equal(opens.length,1);
const oldHost=room(c).hostSlot;
l.disconnect(c,now);assert.notEqual(room(d).hostSlot,oldHost);
const newHost=room(d).hostSlot;
assert(l.resume(c,now));assert.equal(room(c).hostSlot,newHost);
assert.deepEqual(room(c).humans.map(h=>h.ready),[false,false]);
await ready(c);assert.equal(opens.length,1);
let resolve;holdLaunch=new Promise(r=>resolve=r);
const start=ready(d);
l.disconnect(c,now);
resolve();await start;
assert.equal(opens.length,2);assert.equal(ongoing,false);
assert(!room(d).humans.some(h=>h.ready));
assert(l.resume(c,now));holdLaunch=null;
await ready(c);await ready(d);
assert.deepEqual(opens[2],{host:4,accounts:[3,4]});
disabled=true;
await ask(e,'join');assert.match(last(e).error,/unavailable/);
console.log('PASS host Ready persists through addition, both ready orders, busy next lobby, full/disabled, departure resets, host migration/reconnect, in-flight membership guard');